//! Chinese Conical Hat (斗笠) procedural geometry, physics sway,
//! rainbow gradient waves, and shimmering monochromatic luster in Rust.

use crate::color::ColorRGBA;

/// Configuration for the Chinese Conical Hat.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct ChineseHatConfig {
    pub enabled: bool,
    pub mode: i32,       // 0 = static, 1 = rainbow, 2 = shimmering monochrome
    pub color: ColorRGBA,
    pub rib_color: ColorRGBA,
    pub alpha: f32,      // 0.0 .. 1.0
    pub rib_alpha: f32,  // 0.0 .. 1.0
    pub speed: f32,      // animation speed multiplier
    pub scale: f32,      // size scale (1.0 = 100%)
    pub offset_y: f32,   // vertical offset in world units
    pub tilt: bool,      // tilt with movement & aim
}

impl Default for ChineseHatConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            mode: 0,
            color: ColorRGBA { r: 0.95, g: 0.82, b: 0.55, a: 0.65 },
            rib_color: ColorRGBA { r: 0.15, g: 0.12, b: 0.08, a: 0.90 },
            alpha: 0.65,
            rib_alpha: 0.90,
            speed: 1.0,
            scale: 1.0,
            offset_y: 0.0,
            tilt: true,
        }
    }
}

/// A 2D point / vector in screen or world space.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct HatPoint {
    pub x: f32,
    pub y: f32,
}

impl HatPoint {
    pub fn new(x: f32, y: f32) -> Self {
        Self { x, y }
    }
}

/// A triangular facet of the conical hat.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct HatFacet {
    pub apex: HatPoint,
    pub left: HatPoint,
    pub right: HatPoint,
    pub color: ColorRGBA,
}

/// A structural rib line or rim border.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct HatLine {
    pub from: HatPoint,
    pub to: HatPoint,
    pub color: ColorRGBA,
}

pub const MAX_HAT_FACETS: usize = 12;
pub const MAX_HAT_LINES: usize = 32;

/// Mesh generated by Rust for one rendering frame.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct ChineseHatMesh {
    pub facet_count: usize,
    pub facets: [HatFacet; MAX_HAT_FACETS],
    pub line_count: usize,
    pub lines: [HatLine; MAX_HAT_LINES],
}

impl Default for ChineseHatMesh {
    fn default() -> Self {
        let dummy_pt = HatPoint::default();
        let dummy_col = ColorRGBA { r: 0.0, g: 0.0, b: 0.0, a: 0.0 };
        Self {
            facet_count: 0,
            facets: [HatFacet {
                apex: dummy_pt,
                left: dummy_pt,
                right: dummy_pt,
                color: dummy_col,
            }; MAX_HAT_FACETS],
            line_count: 0,
            lines: [HatLine {
                from: dummy_pt,
                to: dummy_pt,
                color: dummy_col,
            }; MAX_HAT_LINES],
        }
    }
}

/// Converts HSV color to RGBA.
pub fn hsv_to_rgba(h: f32, s: f32, v: f32, a: f32) -> ColorRGBA {
    let h = (h.fract() + 1.0).fract() * 6.0;
    let i = h.floor() as i32;
    let f = h - i as f32;
    let p = v * (1.0 - s);
    let q = v * (1.0 - s * f);
    let t = v * (1.0 - s * (1.0 - f));

    let (r, g, b) = match i % 6 {
        0 => (v, t, p),
        1 => (q, v, p),
        2 => (p, v, t),
        3 => (p, q, v),
        4 => (t, p, v),
        _ => (v, p, q),
    };

    ColorRGBA { r, g, b, a }
}

/// Rotates and translates a point from local coordinate space to world space.
#[inline]
fn transform_point(pt: HatPoint, cos_theta: f32, sin_theta: f32, center: HatPoint) -> HatPoint {
    HatPoint {
        x: center.x + pt.x * cos_theta - pt.y * sin_theta,
        y: center.y + pt.x * sin_theta + pt.y * cos_theta,
    }
}

/// Generates the Chinese Conical Hat mesh with mathematical precision.
#[no_mangle]
pub extern "C" fn generate_chinese_hat_mesh(
    body_pos_x: f32,
    body_pos_y: f32,
    body_angle: f32,
    aim_dir_x: f32,
    aim_dir_y: f32,
    base_size: f32,
    anim_time_sec: f32,
    config: &ChineseHatConfig,
    out_mesh: &mut ChineseHatMesh,
) {
    if !config.enabled {
        out_mesh.facet_count = 0;
        out_mesh.line_count = 0;
        return;
    }

    let scale = config.scale.clamp(0.4, 2.5);
    // Conical dimensions derived from authentic Asian conical hats (笠 / 斗笠)
    let hat_width = base_size * 1.45 * scale;
    let hat_height = base_size * 0.58 * scale;
    let hat_sag = hat_height * 0.16; // Slight downward arc along the brim

    // Dynamic tilt calculation
    let mut total_angle = body_angle * std::f32::consts::TAU * 0.65;
    if config.tilt {
        let aim_len = (aim_dir_x * aim_dir_x + aim_dir_y * aim_dir_y).sqrt();
        if aim_len > 0.001 {
            let aim_norm_x = aim_dir_x / aim_len;
            total_angle += aim_norm_x * 0.14; // Subtle lean towards aim
        }
    }

    let cos_t = total_angle.cos();
    let sin_t = total_angle.sin();

    // Resting anchor point on top of the Tee's head
    // Tee body is a circle of radius base_size * 0.5, head crown is at -0.28
    let anchor = HatPoint {
        x: body_pos_x,
        y: body_pos_y - base_size * 0.28 + config.offset_y,
    };

    // Apex in local space
    let local_apex = HatPoint::new(0.0, -hat_height);
    let world_apex = transform_point(local_apex, cos_t, sin_t, anchor);

    // Number of triangular facets radiating out (8 facets, 9 rim points)
    const NUM_SEGMENTS: usize = 8;
    let mut world_rim = [HatPoint::default(); NUM_SEGMENTS + 1];

    for i in 0..=NUM_SEGMENTS {
        let t = i as f32 / NUM_SEGMENTS as f32; // 0.0 .. 1.0
        let lx = -hat_width * 0.5 + hat_width * t;
        // Parabolic brim curve for 3D depth
        let arc_factor = 1.0 - (2.0 * t - 1.0).powi(2);
        let ly = arc_factor * hat_sag;
        world_rim[i] = transform_point(HatPoint::new(lx, ly), cos_t, sin_t, anchor);
    }

    // Build triangular facets
    let speed = config.speed.clamp(0.1, 10.0);
    out_mesh.facet_count = NUM_SEGMENTS;

    for i in 0..NUM_SEGMENTS {
        let t = (i as f32 + 0.5) / NUM_SEGMENTS as f32;

        let facet_color = match config.mode {
            // Mode 1: Rainbow flowing gradient wave across facets
            1 => {
                let hue = (anim_time_sec * speed * 0.35 + t * 0.40).fract();
                hsv_to_rgba(hue, 0.88, 0.98, config.alpha)
            }
            // Mode 2: Shimmering monochromatic luster wave
            2 => {
                let phase = std::f32::consts::TAU * (anim_time_sec * speed * 0.80 - t * 0.75);
                let shimmer = 0.5 + 0.5 * phase.sin(); // 0.0 .. 1.0

                // Interpolate base color with luminous sheen
                let r = (config.color.r * (0.65 + 0.35 * shimmer) + 0.30 * shimmer).min(1.0);
                let g = (config.color.g * (0.65 + 0.35 * shimmer) + 0.30 * shimmer).min(1.0);
                let b = (config.color.b * (0.65 + 0.35 * shimmer) + 0.30 * shimmer).min(1.0);
                ColorRGBA { r, g, b, a: config.alpha }
            }
            // Mode 0: Static color with subtle facet depth shading
            _ => {
                let shade = 0.92 + 0.16 * ((i % 2) as f32);
                ColorRGBA {
                    r: (config.color.r * shade).min(1.0),
                    g: (config.color.g * shade).min(1.0),
                    b: (config.color.b * shade).min(1.0),
                    a: config.alpha,
                }
            }
        };

        out_mesh.facets[i] = HatFacet {
            apex: world_apex,
            left: world_rim[i],
            right: world_rim[i + 1],
            color: facet_color,
        };
    }

    // Build structural rib lines and rim borders
    let mut line_idx = 0;
    let rib_col = ColorRGBA {
        r: config.rib_color.r,
        g: config.rib_color.g,
        b: config.rib_color.b,
        a: config.rib_alpha,
    };

    // 1. Radial ribs from Apex to every rim vertex
    for i in 0..=NUM_SEGMENTS {
        if line_idx < MAX_HAT_LINES {
            out_mesh.lines[line_idx] = HatLine {
                from: world_apex,
                to: world_rim[i],
                color: rib_col,
            };
            line_idx += 1;
        }
    }

    // 2. Brim rim segments
    for i in 0..NUM_SEGMENTS {
        if line_idx < MAX_HAT_LINES {
            out_mesh.lines[line_idx] = HatLine {
                from: world_rim[i],
                to: world_rim[i + 1],
                color: rib_col,
            };
            line_idx += 1;
        }
    }

    // 3. Silhouette slopes
    if line_idx + 1 < MAX_HAT_LINES {
        out_mesh.lines[line_idx] = HatLine {
            from: world_apex,
            to: world_rim[0],
            color: rib_col,
        };
        line_idx += 1;
        out_mesh.lines[line_idx] = HatLine {
            from: world_apex,
            to: world_rim[NUM_SEGMENTS],
            color: rib_col,
        };
        line_idx += 1;
    }

    out_mesh.line_count = line_idx;
}
